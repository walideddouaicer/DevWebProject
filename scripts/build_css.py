"""Concatenate static/css/src/*.css (in name order) into static/css/app.css (PLAN D16).

.venv/bin/python scripts/build_css.py          # write
.venv/bin/python scripts/build_css.py --check  # exit 1 if app.css is stale (used by tests)
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "static" / "css" / "src"
OUT = ROOT / "static" / "css" / "app.css"


def build():
    parts = ["/* Generated by scripts/build_css.py from static/css/src — do not edit. */\n"]
    for path in sorted(SRC.rglob("*.css"), key=lambda p: str(p.relative_to(SRC))):
        parts.append(f"\n/* --- {path.relative_to(SRC)} --- */\n{path.read_text()}")
    return "".join(parts)


if __name__ == "__main__":
    css = build()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == css else 1)
    OUT.write_text(css)
    print(f"{OUT.relative_to(ROOT)}: {len(css) // 1024} KB")

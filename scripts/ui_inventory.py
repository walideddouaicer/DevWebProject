"""Generate docs/ui-inventory.md from the code (PLAN P5.1).

    .venv/bin/python scripts/ui_inventory.py

For every named URL: view, template(s) it renders, role (from the namespace), purpose
(first docstring line). Also lists templates nothing references (orphans).
"""

import inspect
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
os.environ.setdefault("DJANGO_SETTINGS_MODULE", "ensa_project_manager.settings")

import django  # noqa: E402

django.setup()

from django.urls import URLPattern, URLResolver, get_resolver  # noqa: E402

RENDER = re.compile(r"""["']([\w/.-]+\.html)["']""")
ROLE = {
    "student": "étudiant",
    "teacher": "enseignant",
    "administrator": "admin",
    "public": "public",
    "accounts": "public",
    "search": "tous",
}


def walk(patterns, prefix="", ns=""):
    for p in patterns:
        if isinstance(p, URLResolver):
            if p.app_name == "admin":
                continue
            yield from walk(
                p.url_patterns,
                prefix + str(p.pattern),
                f"{ns}{p.namespace}:" if p.namespace else ns,
            )
        elif isinstance(p, URLPattern):
            yield f"{ns}{p.name or ''}", prefix + str(p.pattern), p.callback


def templates_of(func, seen=None):
    """Template names in the view source, following helper calls in the same module."""
    seen = seen or set()
    view_class = getattr(func, "view_class", None)  # check before unwrapping (see below)
    if view_class is not None:
        name = func.view_initkwargs.get("template_name") or getattr(
            view_class, "template_name", None
        )
        return {name} if name else set()
    func = inspect.unwrap(func)
    if func in seen:
        return set()
    seen.add(func)
    try:
        source = inspect.getsource(func)
    except (OSError, TypeError):
        return set()
    found = set(RENDER.findall(source))
    module = inspect.getmodule(func)
    for called in re.findall(r"\b(handle_\w+)\(", source):
        helper = getattr(module, called, None)
        if helper:
            found |= templates_of(helper, seen)
    return found


rows, used = [], set()
for name, route, callback in walk(get_resolver().url_patterns):
    tpls = sorted(t for t in templates_of(callback) if t)
    used.update(tpls)
    func = inspect.unwrap(callback)
    doc = (inspect.getdoc(func) or "").split("\n")[0]
    role = ROLE.get(name.split(":")[0], "tous") if ":" in name else "tous"
    rows.append(
        (role, name, "/" + route, f"{func.__module__}.{func.__name__}", ", ".join(tpls) or "—", doc)
    )

# includes/extends make a template "used" too
all_templates = {}
for path in ROOT.glob("**/templates/**/*.html"):
    if ".venv" in path.parts:
        continue
    rel = str(path).split("/templates/", 1)[1]
    all_templates[rel] = path.read_text(encoding="utf-8")
changed = True
while changed:
    changed = False
    for rel in list(used):
        for ref in re.findall(
            r"""\{%\s*(?:extends|include)\s+["']([^"']+)["']""", all_templates.get(rel, "")
        ):
            if ref not in used:
                used.add(ref)
                changed = True
# Rendered by Django/settings rather than by a view
used |= {"400.html", "403.html", "404.html", "500.html", "registration/lockout.html"}
orphans = sorted(set(all_templates) - used)

out = [
    "# UI inventory",
    "",
    "Generated by `scripts/ui_inventory.py` (PLAN P5.1). Regenerate after URL changes.",
    "",
    f"{len(rows)} routes, {len(all_templates)} templates, {len(orphans)} orphan templates.",
    "",
    "| Role | URL name | Path | View | Template(s) | Purpose |",
    "|---|---|---|---|---|---|",
]
for row in sorted(rows):
    out.append("| " + " | ".join(c.replace("|", "\\|") for c in row) + " |")
out += ["", "## Orphan templates (rendered by nothing)", ""] + [f"- `{o}`" for o in orphans]
(ROOT / "docs" / "ui-inventory.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"{len(rows)} routes, {len(orphans)} orphans")
print("\n".join(orphans))
